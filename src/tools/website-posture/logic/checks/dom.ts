/**
 * DOM hygiene checks for markup constructs that execute or embed content:
 * `javascript:` URLs and `<object>` / `<embed>` elements.
 *
 * As everywhere in this engine, these are observations. A `javascript:` href
 * is a legacy pattern, not a vulnerability, and an `<object>` element is a
 * legitimate way to embed a PDF. Neither is reported as exploitable.
 */

import { CheckContext, CheckOutcome, SecurityCheck, SecurityFinding } from '../../types';
import { createFinding, passed, sanitizeUrlForEvidence } from '../findings';
import { resourcesOfType } from '../page';

/** Schemes that execute or inline content rather than navigating. */
const EXECUTING_SCHEMES = new Set(['javascript:']);
const INLINE_SCHEMES = new Set(['data:', 'blob:', 'filesystem:']);

/** Schemes a browser hands to an external application or handler. */
const KNOWN_EXTERNAL_SCHEMES = new Set([
  'mailto:',
  'tel:',
  'sms:',
  'geo:',
  'ftp:',
  'news:',
  'nntp:',
  'irc:',
  'magnet:',
  'bitcoin:',
  'webcal:',
  'callto:',
  'skype:',
  'whatsapp:',
  'intent:',
  'market:',
  'itms-apps:'
]);

/**
 * `javascript:`, `data:`, and unusual URL schemes in markup.
 *
 * Reported by class, because the classes mean different things: a
 * `javascript:` href is inline script in an attribute, a `data:` href inlines
 * a document the browser will render, and an unrecognized scheme is simply
 * something a reviewer should recognize or question.
 */
export const dangerousUrlSchemeCheck: SecurityCheck = {
  id: 'dangerous-url-schemes',
  category: 'script-security',
  name: 'URL schemes in markup',
  description:
    'Reports javascript:, data:, and other unusual URL schemes used by links and embedded content.',
  severity: 'low',
  scoreWeight: 6,
  modes: ['browser-passive'],
  requires: ['html-body'],

  execute(context: CheckContext): CheckOutcome {
    const findings: SecurityFinding[] = [];

    for (const page of context.pages) {
      const executing = page.links.filter(
        (link) => link.protocol !== null && EXECUTING_SCHEMES.has(link.protocol)
      );
      const inline = page.links.filter(
        (link) => link.protocol !== null && INLINE_SCHEMES.has(link.protocol)
      );
      const unusual = page.links.filter(
        (link) =>
          link.protocol !== null &&
          !link.isNavigable &&
          !EXECUTING_SCHEMES.has(link.protocol) &&
          !INLINE_SCHEMES.has(link.protocol) &&
          !KNOWN_EXTERNAL_SCHEMES.has(link.protocol)
      );

      if (executing.length > 0) {
        findings.push(
          createFinding(this, {
            status: 'warning',
            severity: 'low',
            observation: 'best-practice',
            confidence: 'high',
            source: 'html',
            title: 'Links use javascript: URLs',
            summary: `${executing.length} link${executing.length === 1 ? '' : 's'} use${executing.length === 1 ? 's' : ''} a javascript: URL.`,
            explanation:
              "A javascript: href is inline script carried in an attribute, so a Content-Security-Policy that omits 'unsafe-inline' blocks it, and it cannot be covered by a nonce. It is also a sink: anywhere an href is built from a value a user controls, a javascript: URL becomes script execution. The URLs themselves were not read by this assessment.",
            recommendation:
              'Replace javascript: hrefs with a real href plus a click handler attached in script, or with a <button>. Where hrefs are generated, reject any scheme other than http, https, and mailto.',
            affectedPages: [page.url],
            aggregationKey: 'javascript-url',
            occurrences: executing.length
          })
        );
      }

      if (inline.length > 0) {
        findings.push(
          createFinding(this, {
            status: 'info',
            observation: 'potential-concern',
            confidence: 'low',
            source: 'html',
            title: 'Links target inline content URLs',
            summary: `${inline.length} link${inline.length === 1 ? '' : 's'} point at a data:, blob:, or filesystem: URL.`,
            explanation:
              'These schemes carry the content inside the URL or in browser-held memory rather than fetching it from a server. Browsers already block top-level navigation to a data: URL, and the common uses — a generated download, an inline image — are entirely ordinary. It is listed so a reviewer can confirm each one is intentional.',
            recommendation:
              'Confirm each inline-content link is generated by your own code and not from untrusted input. Prefer a blob: URL with an explicit download attribute for generated files.',
            affectedPages: [page.url],
            aggregationKey: 'inline-content-url',
            occurrences: inline.length
          })
        );
      }

      if (unusual.length > 0) {
        findings.push(
          createFinding(this, {
            status: 'info',
            observation: 'potential-concern',
            confidence: 'low',
            source: 'html',
            title: 'Links use unrecognized URL schemes',
            summary: `${unusual.length} link${unusual.length === 1 ? '' : 's'} use${unusual.length === 1 ? 's' : ''} a scheme this check does not recognize.`,
            explanation:
              'An unrecognized scheme is usually a deliberate deep link into a desktop or mobile application. It is reported so a reviewer can confirm it is expected, since a scheme handler passes its argument to another program. An unusual scheme is not treated as a vulnerability.',
            recommendation:
              'Confirm each scheme is one you intended to link to, and that any value interpolated into such a URL is validated.',
            affectedPages: [page.url],
            aggregationKey: 'unusual-scheme',
            occurrences: unusual.length,
            evidence: [
              {
                label: 'Schemes',
                value: [...new Set(unusual.map((link) => link.protocol))].slice(0, 6).join(', '),
                pageUrl: page.url
              }
            ]
          })
        );
      }
    }

    if (findings.length === 0) {
      return {
        findings: [
          passed(this, {
            summary: 'No javascript:, data:, or unrecognized URL scheme was found in links.',
            explanation:
              'Every link in the markup analyzed uses an ordinary navigable or external scheme, so no link carries inline script or inline content.',
            affectedPages: context.pages.map((page) => page.url)
          })
        ]
      };
    }

    return { findings };
  }
};

