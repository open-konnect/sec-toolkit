export const objectEmbedCheck: SecurityCheck = {
  id: 'object-embed-usage',
  category: 'script-security',
  name: 'Plugin and embedded object content',
  description: 'Reports <object>, <embed>, and <applet> elements and the origins they load from.',
  severity: 'low',
  scoreWeight: 5,
  modes: ['browser-passive'],
  requires: ['html-body'],

  execute(context: CheckContext): CheckOutcome {
    const findings: SecurityFinding[] = [];
    let seen = 0;

    for (const page of context.pages) {
      const embeds = resourcesOfType(page, 'object', 'embed');
      if (embeds.length === 0) continue;
      seen += embeds.length;

      const crossOrigin = embeds.filter((resource) => resource.crossOrigin);
      const insecure = embeds.filter((resource) => resource.protocol === 'http:');

      findings.push(
        insecure.length > 0
          ? createFinding(this, {
              status: 'warning',
              severity: 'medium',
              observation: 'verified-observation',
              confidence: 'high',
              source: 'html',
              title: 'Embedded object loaded over plaintext HTTP',
              summary: `${insecure.length} <object> or <embed> element${insecure.length === 1 ? '' : 's'} reference${insecure.length === 1 ? 's' : ''} an http:// URL.`,
              explanation:
                'Embedded object content is treated as active content: in the contexts where a plugin or renderer handles it, substituted content can run in the page. Over plaintext HTTP anyone on the network path can substitute it, and browsers block the load outright on a secure page.',
              recommendation:
                'Serve embedded content over HTTPS, and prefer a modern element — <iframe>, <video>, <img> — over <object> or <embed> where one applies.',
              affectedPages: [page.url],
              aggregationKey: 'http-source',
              occurrences: insecure.length,
              evidence: insecure.slice(0, 3).map((resource) => ({
                label: `<${resource.element}>`,
                value: sanitizeUrlForEvidence(resource.url ?? resource.rawUrl),
                pageUrl: page.url
              }))
            })
          : createFinding(this, {
              status: 'info',
              observation: 'potential-concern',
              confidence: 'medium',
              source: 'html',
              title: 'Page embeds object or plugin content',
              summary: `${embeds.length} <object> or <embed> element${embeds.length === 1 ? '' : 's'} on this page, ${crossOrigin.length} of them cross-origin.`,
              explanation:
                'These elements hand a resource to a renderer or plugin, which historically has been a weaker security boundary than an iframe and is not constrained by script-src. Embedding a PDF or an SVG this way is perfectly normal, so this is an attack-surface note rather than a defect.',
              recommendation:
                "Declare object-src 'none' in your CSP if you do not need plugin content, and replace these elements with <iframe>, <img>, or <video> where that is possible.",
              affectedPages: [page.url],
              aggregationKey: crossOrigin.length > 0 ? 'cross-origin' : 'same-origin',
              occurrences: embeds.length,
              evidence: embeds.slice(0, 3).map((resource) => ({
                label: `<${resource.element}> · ${resource.host ?? 'same origin'}`,
                value: sanitizeUrlForEvidence(resource.url ?? resource.rawUrl),
                pageUrl: page.url
              }))
            })
      );
    }

    if (seen === 0) {
      return {
        findings: [
          passed(this, {
            summary: 'No <object> or <embed> element was found.',
            explanation:
              'The markup analyzed embeds no plugin or object content, so that surface does not exist on these pages.',
            affectedPages: context.pages.map((page) => page.url)
          })
        ]
      };
    }

    return { findings };
  }
};
